USE ROLE ACCOUNTADMIN;

-- Warehouse (smallest size, pauses after 60 s to save credits)
CREATE WAREHOUSE IF NOT EXISTS READNEXT_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

-- Database and schemas
CREATE DATABASE IF NOT EXISTS READNEXT;
CREATE SCHEMA IF NOT EXISTS READNEXT.RAW;
CREATE SCHEMA IF NOT EXISTS READNEXT.STAGING;
CREATE SCHEMA IF NOT EXISTS READNEXT.MARTS;

-- Role for the project
CREATE ROLE IF NOT EXISTS READNEXT_ROLE;
GRANT USAGE, OPERATE ON WAREHOUSE READNEXT_WH TO ROLE READNEXT_ROLE;
GRANT ALL ON DATABASE READNEXT TO ROLE READNEXT_ROLE;
GRANT ALL ON ALL SCHEMAS IN DATABASE READNEXT TO ROLE READNEXT_ROLE;
GRANT ALL ON FUTURE SCHEMAS IN DATABASE READNEXT TO ROLE READNEXT_ROLE;

-- Let your own user see the data in Snowsight
SET my_user = CURRENT_USER();
GRANT ROLE READNEXT_ROLE TO USER IDENTIFIER($my_user);

-- Service user for Python and dbt (key pair, no password)
CREATE USER IF NOT EXISTS READNEXT_SVC
    TYPE = SERVICE
    DEFAULT_ROLE = READNEXT_ROLE
    DEFAULT_WAREHOUSE = READNEXT_WH
    DEFAULT_NAMESPACE = READNEXT.RAW
    RSA_PUBLIC_KEY = '<PASTE_PUBLIC_KEY_HERE>';

GRANT ROLE READNEXT_ROLE TO USER READNEXT_SVC;

-- Check: RSA_PUBLIC_KEY_FP should have a value
DESC USER READNEXT_SVC;